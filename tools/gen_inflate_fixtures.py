"""Writes tests/unit/inflate_fixtures.hpp: synthetic zlib streams (Python's
zlib) for the port's inflate (`native.cpp` `inflate_zlib_exact`): a stored
block, fixed codes, dynamic codes, and the text they hold, made by the same
generator as `fixture_text` in tests/unit/shader_tests.cpp.

Usage: python -I tools/gen_inflate_fixtures.py
"""
import pathlib
import zlib

WORDS = [b"lane ", b"mask ", b"wave ", b"exec ", b"vgpr ", b"sgpr ", b"scalar ", b"vector ",
         b"export ", b"image ", b"sample ", b"buffer ", b"\x00\x01\x02", b"\xff\xfe", b"0123456789", b"\n"]


def fixture_text(n, seed):
    out = bytearray()
    x = seed
    while len(out) < n:
        x = (x * 1103515245 + 12345) & 0xFFFFFFFF
        out += WORDS[(x >> 16) & 15]
    return bytes(out[:n])


def stream(data, level, strategy):
    c = zlib.compressobj(level, zlib.DEFLATED, 15, 9, strategy)
    return c.compress(data) + c.flush()


def array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"inline constexpr std::uint8_t {name}[] = {{\n    " + ",\n    ".join(rows) + "};\n"


def main():
    cases = [
        ("STORED", 300, 1, 0, zlib.Z_DEFAULT_STRATEGY),
        ("FIXED", 8000, 2, 6, zlib.Z_FIXED),
        ("DYNAMIC", 40000, 3, 9, zlib.Z_DEFAULT_STRATEGY),
    ]
    text = ["// SPDX-License-Identifier: GPL-3.0-or-later",
            "// Generated by tools/gen_inflate_fixtures.py (Python's zlib): synthetic",
            "// streams of `fixture_text(size, seed)`.",
            "#pragma once", "", "#include <cstdint>", ""]
    for name, size, seed, level, strategy in cases:
        z = stream(fixture_text(size, seed), level, strategy)
        text.append(f"inline constexpr std::uint32_t {name}_SIZE = {size}, {name}_SEED = {seed};")
        text.append(array(f"{name}_ZLIB", z))
    out = pathlib.Path(__file__).resolve().parent.parent / "tests" / "unit" / "inflate_fixtures.hpp"
    out.write_text("\n".join(text))
    print(out, out.stat().st_size)


if __name__ == "__main__":
    main()
