using u64 = std::uint64_t;

std::string read_file(const fs::path& p) {
    std::ifstream f(p, std::ios::binary);
    return std::string((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
}

std::vector<std::string> lines_of(const std::string& text) {
    std::vector<std::string> out;
    std::istringstream in(text);
    std::string l;
    while (std::getline(in, l)) {
        if (!l.empty() && l.back() == '\r') {
            l.pop_back();
        }
        out.push_back(l);
    }
    return out;
}

std::string hex(u64 v) {
    char b[32];
    std::snprintf(b, sizeof b, "0x%llx", static_cast<unsigned long long>(v));
    return b;
}


struct Rng {
    u64 s;
    u64 next() {
        u64 z = (s += 0x9E3779B97F4A7C15ull);
        z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ull;
        z = (z ^ (z >> 27)) * 0x94D049BB133111EBull;
        return z ^ (z >> 31);
    }
    u64 below(u64 n) { return n == 0 ? 0 : next() % n; }
    u64 between(u64 lo, u64 hi) { return lo + below(hi - lo + 1); }   
    bool chance(int pct) { return static_cast<int>(below(100)) < pct; }
};

constexpr u64 K64 = 64 << 10;

u64 saturating_sub(u64 a, u64 b) { return a > b ? a - b : 0; }
constexpr u64 BASE = 0x200000000000ull;
constexpr u64 SLOT = 0x100000000ull;   

struct Place {
    std::string name;
    u64 bytes;
    bool view_memory;   
};

struct ShadowGen {
    std::string name;
    u64 len;
    u64 phase;   
    std::vector<std::pair<u64, u64>> declared;   
};


long long edge(Rng& r, const ShadowGen& s) {
    long long at;
    if (r.chance(25)) {
        at = static_cast<long long>(r.chance(50) ? 0 : s.len);
    } else {
        u64 pages = (s.phase + s.len) / K64 + 1;
        at = static_cast<long long>(r.below(pages + 1) * K64) - static_cast<long long>(s.phase);
    }
    return at + static_cast<long long>(r.below(3)) - 1;
}

std::string generate(u64 seed) {
    Rng r{seed * 0x2545F4914F6CDD1Dull + 1};
    std::ostringstream o;
    o << "# generated by dirty-diff gen " << seed << "\n";

    if (r.chance(15)) {
        static const char* switches[][2] = {{"VICTORY_ASK_ONCE", "0"},   {"VICTORY_RELAY", "0"},          {"VICTORY_VIEW_GUARD", "0"},
                                            {"VICTORY_GUARD_HOLES", "0"}, {"VICTORY_GUARD_ASK", "1"},      {"VICTORY_RELAY", "1"},
                                            {"VICTORY_WIDE_BACK", "0"},   {"VICTORY_KEEP_SNAPSHOTS", "1"}, {"VICTORY_DIRECT_WRITES", "0"},
                                            {"VICTORY_FAST_TITLE_ACCESS", "0"}};
        auto& s = switches[r.below(std::size(switches))];
        o << "env " << s[0] << " " << s[1] << "\n";
    }
    std::vector<Place> places;
    u64 slot = 0;
    auto next_slot = [&] { return BASE + (slot++) * SLOT; };


    int watched = 1 + static_cast<int>(r.below(2));
    for (int i = 0; i < watched; ++i) {
        u64 at = next_slot();
        u64 bytes = r.between(2, 24) * K64;
        std::string name = "W" + std::to_string(i);
        o << "region " << name << " watched " << hex(at) << " " << hex(bytes) << "\n";
        places.push_back({name, bytes, false});
        if (r.chance(35)) {
            u64 at2 = at + bytes + r.below(3) * K64;
            u64 bytes2 = r.between(1, 12) * K64;
            std::string name2 = name + "n";
            o << "region " << name2 << " watched " << hex(at2) << " " << hex(bytes2) << "\n";
            places.push_back({name2, bytes2, false});
        }
    }


    std::optional<Place> reserve;
    if (r.chance(50)) {
        u64 bytes = r.between(2, 16) * K64;
        o << "region R reserve " << hex(next_slot()) << " " << hex(bytes) << "\n";
        for (int k = 0, n = static_cast<int>(r.between(1, 4)); k < n; ++k) {
            u64 off = r.below(bytes / 4096) * 4096;
            u64 len = std::min(bytes - off, r.between(1, 40) * 4096);
            o << "commit R " << hex(off) << " " << hex(len) << "\n";
        }
        reserve = Place{"R", bytes, false};
        places.push_back(*reserve);
    }
    if (r.chance(30)) {
        u64 bytes = r.between(1, 8) * K64;
        o << "region P plain " << hex(next_slot()) << " " << hex(bytes) << "\n";
        places.push_back({"P", bytes, false});
    }

    if (r.chance(65)) {
        u64 blocks = r.between(1, 6);
        o << "section S " << hex(blocks * K64) << "\n";
        int views = 2 + static_cast<int>(r.below(2));
        for (int v = 0; v < views; ++v) {
            u64 first = r.below(blocks);
            u64 count = r.between(1, blocks - first);
            std::string name = "V" + std::to_string(v);
            o << "view " << name << " S " << hex(first * K64) << " " << hex(next_slot()) << " " << hex(count * K64) << "\n";
            places.push_back({name, count * K64, true});
        }
    }

    std::vector<bool> mapped;
    u64 ph_section_blocks = 0;
    if (r.chance(45)) {
        u64 blocks = r.between(2, 8);
        ph_section_blocks = r.between(1, blocks);
        o << "section T " << hex(ph_section_blocks * K64) << "\n";
        o << "placeholder H " << hex(next_slot()) << " " << blocks << "\n";
        mapped.assign(blocks, false);
        for (u64 b = 0; b < blocks; ++b) {
            if (r.chance(50)) {
                o << "map H " << b << " T " << hex(r.below(ph_section_blocks) * K64) << "\n";
                mapped[b] = true;
            }
        }
        places.push_back({"H", blocks * K64, true});
    }


    std::vector<ShadowGen> shadows;
    struct Spot {
        size_t place;
        u64 off, len;
    };
    std::vector<Spot> spots;
    int nshadows = 2 + static_cast<int>(r.below(5));
    for (int i = 0; i < nshadows; ++i) {
        Spot s;
        if (!spots.empty() && r.chance(35)) {

            const Spot& outer = spots[r.below(spots.size())];
            s.place = outer.place;
            s.off = outer.off + r.below(outer.len);
            s.len = std::max<u64>(1, r.below(outer.len - (s.off - outer.off) + K64));
            s.len = std::min(s.len, places[s.place].bytes - s.off);
        } else {
            s.place = r.below(places.size());
            u64 bytes = places[s.place].bytes;
            switch (r.below(4)) {
                case 0: s.off = 0; break;
                case 1: s.off = r.below(bytes / K64) * K64; break;
                case 2: s.off = r.below(bytes / 4096) * 4096; break;
                default: s.off = r.below(bytes); break;
            }
            u64 room = bytes - s.off;
            s.len = r.chance(40) ? room : std::max<u64>(1, r.below(room) + 1);
        }
        if (s.len == 0) {
            s.len = 1;
        }
        std::string name = "s" + std::to_string(i);
        o << "shadow " << name << " " << places[s.place].name << " " << hex(s.off) << " " << hex(s.len) << "\n";
        spots.push_back(s);
        shadows.push_back({name, s.len, s.off % K64, {}});
    }

    auto any_range = [&](const ShadowGen& s) {


        u64 len = s.len;
        if (r.chance(35)) {
            long long a = edge(r, s), b = edge(r, s);
            if (a > b) std::swap(a, b);
            if (a == b) ++b;
            return std::make_pair(a, static_cast<u64>(b - a));
        }
        long long off;
        switch (r.below(6)) {
            case 0: off = 0; break;
            case 1: off = -static_cast<long long>(r.between(1, 3 * K64)); break;
            case 2: off = static_cast<long long>(r.below(len / K64 + 1) * K64); break;
            default: off = static_cast<long long>(r.below(len)); break;
        }
        u64 n = r.chance(40) ? len + (off < 0 ? static_cast<u64>(-off) : 0) : r.between(1, len + K64);
        return std::make_pair(off, n);
    };
    auto off_str = [](long long v) { return v < 0 ? "-" + hex(static_cast<u64>(-v)) : hex(static_cast<u64>(v)); };

    u64 prepare = 0;
    u64 seed_bytes = 1;
    bool once_standing = false;
    int ops = 40 + static_cast<int>(r.below(90));
    for (int i = 0; i < ops; ++i) {
        u64 what = r.below(100);
        if (what < 26) {

            const Place& p = places[r.below(places.size())];
            u64 off = r.below(p.bytes);
            u64 len;
            switch (r.below(10)) {
                case 0: case 1: case 2: case 3: case 4: len = r.between(1, 256); break;
                case 5: case 6: case 7: len = r.between(1, 16 << 10); break;
                default: len = r.between(1, 192 << 10); break;
            }
            len = std::min(len, p.bytes - off);
            bool kernel = p.view_memory && r.chance(30);
            o << (kernel ? "kwrite " : "write ") << p.name << " " << hex(off) << " " << hex(len) << " " << seed_bytes++ << "\n";
            if (once_standing && !p.view_memory && r.chance(50)) {
                o << "wrote " << p.name << " " << hex(off) << " " << hex(len) << "\n";
            }
        } else if (what < 48) {
            const ShadowGen& s = shadows[r.below(shadows.size())];
            auto [off, n] = any_range(s);
            o << "refresh " << s.name << " " << off_str(off) << " " << hex(n) << "\n";
        } else if (what < 56) {
            o << "flush";
            for (int k = 0, n = static_cast<int>(r.between(2, 4)); k < n; ++k) {
                const ShadowGen& s = shadows[r.below(shadows.size())];
                auto [off, len] = any_range(s);
                o << " " << s.name << " " << off_str(off) << " " << hex(len);
            }
            o << "\n";
        } else if (what < 70) {

            ShadowGen& s = shadows[r.below(shadows.size())];
            if (!s.declared.empty() && r.chance(65)) {
                u64 how = r.below(10);
                if (how < 4) {


                    o << "relay_back";
                    for (auto [off, len] : s.declared) {
                        o << " " << s.name << " " << hex(off) << " " << hex(len);
                    }
                    o << "\ngpu_done " << s.name;
                    for (auto [off, len] : s.declared) {
                        o << " " << hex(off) << " " << hex(len);
                    }
                    o << "\n";
                    s.declared.clear();
                } else if (how < 7) {
                    o << "hand_back";
                    for (auto [off, len] : s.declared) {
                        o << " " << s.name << " " << hex(off) << " " << hex(len);
                    }
                    o << "\n";
                    s.declared.clear();
                } else if (how < 8) {
                    auto d = s.declared[r.below(s.declared.size())];
                    o << "copy_back " << s.name << " " << hex(d.first) << " " << hex(d.second) << "\n";
                } else if (how < 9) {
                    auto [off, n] = any_range(s);
                    o << "merge_under " << s.name << " " << off_str(off) << " " << hex(n) << " " << r.between(0, 600) << "\n";
                } else {
                    auto d = s.declared[r.below(s.declared.size())];
                    o << "gpu_done " << s.name << " " << hex(d.first) << " " << hex(d.second) << "\n";
                    s.declared.erase(std::find(s.declared.begin(), s.declared.end(), d));
                }
            } else {
                if (r.chance(70)) {
                    o << "prepare " << ++prepare << "\n";
                }
                if (r.chance(40) && !s.declared.empty()) {

                    auto d = s.declared[r.below(s.declared.size())];
                    o << "gpu_declare " << s.name << " " << hex(d.first) << " " << hex(d.second) << "\n";
                    s.declared.push_back(d);
                }
                u64 off = r.below(s.len);
                u64 len = std::max<u64>(1, std::min(s.len - off, r.between(1, 2 * K64)));
                if (r.chance(35)) {

                    long long a = std::clamp<long long>(edge(r, s), 0, static_cast<long long>(s.len) - 1);
                    long long b = std::clamp<long long>(edge(r, s), 1, static_cast<long long>(s.len));
                    if (a >= b) std::swap(a, b);
                    if (a == b) b = a + 1;
                    off = static_cast<u64>(a);
                    len = static_cast<u64>(b - a);
                }
                o << "gpu_declare " << s.name << " " << hex(off) << " " << hex(len) << "\n";
                s.declared.emplace_back(off, len);

                o << "snapshots\n";
                for (int k = 0, writes = static_cast<int>(r.below(4)); k < writes; ++k) {

                    u64 woff = off + r.below(len);
                    u64 room = len - (woff - off);
                    u64 wlen = r.chance(50) ? r.between(1, std::min<u64>(room, 64)) : r.between(1, room + (r.chance(15) ? 4096 : 0));
                    o << "gpu_write " << s.name << " " << hex(woff) << " " << hex(wlen) << " " << seed_bytes++ << "\n";
                }
            }
        } else if (what < 74) {
            const ShadowGen& s = shadows[r.below(shadows.size())];
            auto [off, n] = any_range(s);
            o << "stale " << s.name << " " << off_str(off) << " " << hex(n) << "\n";
        } else if (what < 77 && reserve) {
            u64 off = r.below(reserve->bytes / 4096) * 4096;
            u64 len = std::min(reserve->bytes - off, r.between(1, 24) * 4096);
            o << (r.chance(55) ? "commit R " : "decommit R ") << hex(off) << " " << hex(len) << "\n";
        } else if (what < 84 && !mapped.empty()) {
            u64 b = r.below(mapped.size());
            if (mapped[b]) {
                o << "unmap H " << b << "\n";
            } else {
                o << "map H " << b << " T " << hex(r.below(ph_section_blocks) * K64) << "\n";
            }
            mapped[b] = !mapped[b];
        } else if (what < 90) {
            if (once_standing && r.chance(50)) {
                o << "ask_once_end\n";
                once_standing = false;
            } else {
                o << (r.chance(60) ? "ask_once" : "ask_ahead");
                for (int k = 0, n = static_cast<int>(r.between(1, 4)); k < n; ++k) {
                    const ShadowGen& s = shadows[r.below(shadows.size())];
                    auto [off, len] = any_range(s);
                    o << " " << s.name << " " << off_str(off) << " " << hex(len);
                }
                o << "\n";
                once_standing = true;   
                if (r.chance(40)) {
                    o << "ask_ahead_done\n";
                }
            }
        } else if (what < 94) {
            o << "check\n";
        } else {

            ShadowGen& s = shadows[r.below(shadows.size())];
            if (!s.declared.empty()) {
                o << "gpu_done " << s.name;
                for (auto [off, len] : s.declared) {
                    o << " " << hex(off) << " " << hex(len);
                }
                o << "\n";
                s.declared.clear();
            }
        }
    }
    o << "end\n";
    return o.str();
}


struct Outcome {
    bool match = true;
    std::string detail;
    int ops = 0;
    int drift_lines = 0;   
    int fresher = 0;       
};

std::map<std::string, std::string> fields_of(const std::string& state) {
    std::map<std::string, std::string> f;
    std::istringstream words(state);
    std::string w;
    while (words >> w) {
        auto eq = w.find('=');
        if (eq != std::string::npos) {
            f[w.substr(0, eq)] = w.substr(eq + 1);
        } else {
            f["@" + w] = "";
        }
    }
    return f;
}


bool never_staler(const std::string& o, const std::string& c, const std::string& op) {
    if (o.rfind("  state", 0) != 0 || c.rfind("  state", 0) != 0) {
        return false;
    }
    auto fo = fields_of(o), fc = fields_of(c);
    for (const char* k : {"title", "pending"}) {
        if (fo[k] != fc[k]) {
            return false;
        }
    }
    for (const auto& [k, v] : fo) {
        if (k[0] == '@' && !fc.count(k)) {
            return false;   
        }
    }
    if (!fo.count("drift") || !fc.count("drift")) {
        return false;
    }
    bool refreshed = op.find(" refresh ") != std::string::npos || op.find(" flush ") != std::string::npos;
    return !refreshed || std::stoull(fc["drift"]) <= std::stoull(fo["drift"]);
}


bool contents_only = false;


bool title_only = false;


bool final_only = false;

std::vector<std::string> after_last_check(const std::vector<std::string>& lines) {
    size_t from = 0;
    for (size_t i = 0; i < lines.size(); ++i) {
        const auto& l = lines[i];
        if (!l.empty() && l[0] == '#' && (l.find(" check") != std::string::npos || l.find(" end") != std::string::npos)) {
            from = i;   
        }
    }
    return std::vector<std::string>(lines.begin() + static_cast<std::ptrdiff_t>(from), lines.end());
}


std::vector<std::string> contents_of(const std::vector<std::string>& lines) {
    std::vector<std::string> out;
    for (const auto& l : lines) {
        if (!l.empty() && l[0] == '#') {
            out.push_back(l);
        } else if (l.rfind("  state ", 0) == 0) {
            std::istringstream words(l);
            std::string w, kept = "  state";
            while (words >> w) {
                if (w == "state" || w.rfind("mode=", 0) == 0 || w.rfind("uncopied=", 0) == 0 || w.rfind("pages=", 0) == 0) {
                    continue;
                }
                kept += " " + w;
            }
            out.push_back(kept);
        } else if (l.rfind("  title write", 0) == 0 || l.rfind("  back ", 0) == 0 || l.rfind("  wrote ", 0) == 0 || l.rfind("  error", 0) == 0 ||
                   l.rfind("  ok ", 0) == 0 || l.rfind("  gpu wrote", 0) == 0) {
            out.push_back(l);
        } else if (!title_only && l.rfind("  card ", 0) == 0 && l.find(" vram=") != std::string::npos) {


            out.push_back(l.substr(0, l.find(" hashes=")));
        }
    }
    return out;
}

Outcome compare(const fs::path& a, const fs::path& b) {
    Outcome out;
    auto la = lines_of(read_file(a / "log.txt"));
    auto lb = lines_of(read_file(b / "log.txt"));
    if (contents_only) {
        la = contents_of(la);
        lb = contents_of(lb);
        if (final_only) {
            la = after_last_check(la);
            lb = after_last_check(lb);
        }
    }
    for (const auto& l : la) {
        if (!l.empty() && l[0] == '#') {
            ++out.ops;
        }
        auto d = l.find(" drift=");
        if (l.rfind("  state ", 0) == 0 && d != std::string::npos) {
            std::string v = l.substr(d + 7);
            v = v.substr(0, v.find(' '));
            if (v != "0") {
                ++out.drift_lines;
            }
        }
    }
    std::string op = "(before the first operation)";
    for (size_t i = 0; i < std::max(la.size(), lb.size()); ++i) {
        const std::string* x = i < la.size() ? &la[i] : nullptr;
        const std::string* y = i < lb.size() ? &lb[i] : nullptr;
        if (x && y && *x == *y) {
            if (!x->empty() && (*x)[0] == '#') {
                op = *x;
            }
            continue;
        }
        if (contents_only && x && y && never_staler(*x, *y, op)) {
            ++out.fresher;
            continue;
        }
        out.match = false;
        out.detail = "first mismatch at log line " + std::to_string(i + 1) + ", in operation " + op + "\n  oracle: " +
                     (x ? *x : std::string("<end of log>")) + "\n  c++   : " + (y ? *y : std::string("<end of log>"));
        return out;
    }
    std::set<std::string> bins;
    for (const fs::path& dir : {a, b}) {
        std::error_code ec;
        if (!fs::is_directory(dir, ec)) {
            out.match = false;
            out.detail = "no output in " + dir.string();
            return out;
        }
        for (const auto& e : fs::directory_iterator(dir)) {
            if (e.path().extension() == ".bin") {
                bins.insert(e.path().filename().string());
            }
        }
    }
    for (const auto& name : bins) {


        if (contents_only && name.rfind("shadow-", 0) == 0) {
            continue;
        }
        if (!fs::exists(a / name) || !fs::exists(b / name)) {
            out.match = false;
            out.detail = name + " exists on one side only";
            return out;
        }
        auto x = read_file(a / name), y = read_file(b / name);
        if (x == y) {
            continue;
        }
        size_t k = 0;
        while (k < x.size() && k < y.size() && x[k] == y[k]) {
            ++k;
        }
        char buf[200];
        std::snprintf(buf, sizeof buf, "%s: first differing byte at offset %s (oracle %s, c++ %s; sizes %zu / %zu)", name.c_str(), hex(k).c_str(),
                      k < x.size() ? hex(static_cast<unsigned char>(x[k])).c_str() : "-", k < y.size() ? hex(static_cast<unsigned char>(y[k])).c_str() : "-",
                      x.size(), y.size());
        out.match = false;
        out.detail = buf;
        return out;
    }
    return out;
}


struct Ran {
    DWORD exit_code = 0;
    double ms = 0;
};


Ran run_exe(const fs::path& exe_in, const fs::path& scenario_in, const fs::path& out_in, DWORD_PTR mask = 0) {
    auto native = [](const fs::path& p) { return fs::absolute(p).make_preferred().wstring(); };
    std::wstring exe = native(exe_in);
    std::wstring cmd = L"\"" + exe + L"\" \"" + native(scenario_in) + L"\" \"" + native(out_in) + L"\"";
    STARTUPINFOW si{};
    si.cb = sizeof si;
    PROCESS_INFORMATION pi{};
    auto started = std::chrono::steady_clock::now();
    if (!CreateProcessW(exe.c_str(), cmd.data(), nullptr, nullptr, FALSE, mask ? CREATE_SUSPENDED : 0, nullptr, nullptr, &si, &pi)) {
        std::fprintf(stderr, "dirty-diff: cannot start %ls (error %lu)\n", exe.c_str(), GetLastError());
        return Ran{0xFFFFFFFF, 0};
    }
    if (mask) {
        SetProcessAffinityMask(pi.hProcess, mask);
        ResumeThread(pi.hThread);
    }
    WaitForSingleObject(pi.hProcess, INFINITE);
    Ran ran;
    GetExitCodeProcess(pi.hProcess, &ran.exit_code);
    ran.ms = std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - started).count();
    CloseHandle(pi.hProcess);
    CloseHandle(pi.hThread);
    return ran;
}


bool run_one(const fs::path& scenario, const fs::path& oracle, const fs::path& cpp, const fs::path& work, const std::string& label, bool keep) {
    fs::remove_all(work);
    fs::create_directories(work);
    auto a = run_exe(oracle, scenario, work / "oracle");
    auto b = run_exe(cpp, scenario, work / "cpp");
    Outcome c;
    if (a.exit_code != 0 || b.exit_code != 0) {


        c = compare(work / "oracle", work / "cpp");
        if (c.match && a.exit_code != b.exit_code) {
            c.match = false;
            c.detail = "exit codes differ: oracle " + hex(a.exit_code) + ", c++ " + hex(b.exit_code);
        }
    } else {
        c = compare(work / "oracle", work / "cpp");
    }
    std::string fresher = contents_only ? "fresher=" + std::to_string(c.fresher) + " " : "";
    std::printf("%-28s %s ops=%-4d drift_states=%-3d %soracle=%.1fms c++=%.1fms%s\n", label.c_str(), c.match ? "MATCH   " : "MISMATCH", c.ops,
                c.drift_lines, fresher.c_str(), a.ms, b.ms,
                (a.exit_code || b.exit_code) ? (" exit=" + hex(a.exit_code) + "/" + hex(b.exit_code)).c_str() : "");
    if (!c.match) {
        std::printf("  %s\n  (kept in %s)\n", c.detail.c_str(), work.string().c_str());
    } else if (!keep) {
        fs::remove_all(work);
    }
    std::fflush(stdout);
    return c.match;
}


