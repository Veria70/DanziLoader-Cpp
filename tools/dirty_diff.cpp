int run_main(int argc, char** argv) {
    if (argc >= 2 && (std::string(argv[1]) == "--contents" || std::string(argv[1]) == "--title" || std::string(argv[1]) == "--final")) {

        contents_only = true;
        title_only = std::string(argv[1]) != "--contents";
        final_only = std::string(argv[1]) == "--final";
        --argc;
        ++argv;
    }
    if (argc < 2) {
        return usage();
    }
    std::string cmd = argv[1];
    if (cmd == "gen" && argc == 4) {
        std::ofstream(argv[3], std::ios::binary) << generate(std::stoull(argv[2]));
        return 0;
    }
    if (cmd == "genbench" && argc == 3) {
        write_bench(argv[2]);
        return 0;
    }
    if (cmd == "genutil" && argc == 4) {
        std::ofstream(argv[3], std::ios::binary) << generate_util(std::stoull(argv[2]));
        return 0;
    }
    if (cmd == "gencardbench" && argc == 3) {
        write_card_bench(argv[2]);
        return 0;
    }
    if (cmd == "bench" && (argc == 7 || argc == 8)) {
        return bench(argv[2], argv[3], argv[4], argv[5], std::stoi(argv[6]), static_cast<DWORD_PTR>(argc == 8 ? std::stoull(argv[7], nullptr, 16) : 0xFFFF));
    }
    if (cmd == "compare" && argc == 4) {
        auto c = compare(argv[2], argv[3]);
        std::printf("%s ops=%d drift_states=%d\n%s\n", c.match ? "MATCH" : "MISMATCH", c.ops, c.drift_lines, c.detail.c_str());
        return c.match ? 0 : 1;
    }
    if (cmd == "run" && argc == 6) {
        return run_one(argv[2], argv[3], argv[4], argv[5], fs::path(argv[2]).filename().string(), true) ? 0 : 1;
    }
    if (cmd == "suite" && argc == 6) {
        std::vector<fs::path> files;
        for (const auto& e : fs::directory_iterator(argv[2])) {
            if (e.path().extension() == ".txt") {
                files.push_back(e.path());
            }
        }
        std::sort(files.begin(), files.end());
        int failed = 0;
        for (const auto& f : files) {
            failed += run_one(f, argv[3], argv[4], fs::path(argv[5]) / f.stem(), f.filename().string(), false) ? 0 : 1;
        }
        std::printf("suite: %zu scenarios, %d mismatched\n", files.size(), failed);
        return failed ? 1 : 0;
    }
    if ((cmd == "fuzz" || cmd == "utilfuzz") && argc == 7) {
        bool util = cmd == "utilfuzz";
        u64 first = std::stoull(argv[2]), count = std::stoull(argv[3]);
        fs::path work = argv[6];
        fs::create_directories(work);
        u64 done = 0;
        for (u64 seed = first; seed < first + count; ++seed) {
            fs::path dir = work / ("seed-" + std::to_string(seed));
            fs::create_directories(dir.parent_path());
            fs::path scenario = work / ("seed-" + std::to_string(seed) + ".txt");
            std::ofstream(scenario, std::ios::binary) << (util ? generate_util(seed) : generate(seed));
            bool ok = run_one(scenario, argv[4], argv[5], dir, "seed " + std::to_string(seed), false);
            ++done;
            if (!ok) {
                std::printf("fuzz: stopped at the first mismatch (seed %llu) after %llu scenarios\n", static_cast<unsigned long long>(seed),
                            static_cast<unsigned long long>(done));
                return 1;
            }
            fs::remove(scenario);
        }
        std::printf("fuzz: %llu scenarios, all matched\n", static_cast<unsigned long long>(done));
        return 0;
    }
    return usage();
}
