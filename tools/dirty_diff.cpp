void write_card_bench(const fs::path& dir) {
    fs::create_directories(dir);
    Rng r{0xCA4D5};
    auto put = [&](const std::string& name, const std::string& text) { std::ofstream(dir / (name + ".txt"), std::ios::binary) << text; };
    const u64 MB = 1 << 20;
    const u64 CARD_BASE = 0x202100000000ull;
    struct Shape {
        const char* name;
        const char* about;
        const char* env;
        u64 size;
        int rounds;
        int title_writes;       
        int shader_writes;      
        u64 write_len;          
        bool spread;            
        int ranges;             
        bool relay = false;     
    };
    const Shape shapes[] = {
        {"d1-64mb-sparse", "64 MiB carded copy, declared whole, 16 small shader writes", nullptr, 64 * MB, 30, 2, 16, 0, false, 0},
        {"d2-64mb-dense", "64 MiB carded copy, declared whole, 1,024 pieces written (4 KiB each)", nullptr, 64 * MB, 20, 2, 1024, 4096, true, 0},
        {"d3-256mb-sparse", "256 MiB carded copy, declared whole, 16 small shader writes", nullptr, 256 * MB, 20, 2, 16, 0, false, 0},
        {"d4-512mb-overflow", "512 MiB carded copy, 3,000 pieces written: past the ring's 2,048", nullptr, 512 * MB, 8, 2, 3000, 256, true, 0},
        {"d5-128mb-512-ranges", "128 MiB carded copy, 512 small declared ranges, 256 title pages sent up", nullptr, 128 * MB, 20, 256, 64, 64, false,
         512},
        {"d6-64mb-dense-no-ring", "d2 with VICTORY_CARD_INLINE_FETCH=0: every piece in one fetch", "VICTORY_CARD_INLINE_FETCH", 64 * MB, 20, 2, 1024,
         4096, true, 0},


        {"r1-64mb-sparse-relay", "d1 sent ahead, one in the air", nullptr, 64 * MB, 30, 2, 16, 0, false, 0, true},
        {"r2-64mb-dense-relay", "d2 sent ahead, one in the air", nullptr, 64 * MB, 20, 2, 1024, 4096, true, 0, true},
        {"r3-128mb-ranges-relay", "d5 sent ahead, one in the air", nullptr, 128 * MB, 20, 256, 64, 64, false, 512, true},
        {"r4-64mb-dense-relay-no-ring", "r2 with VICTORY_CARD_INLINE_FETCH=0: every piece in the relay's fetch", "VICTORY_CARD_INLINE_FETCH", 64 * MB, 20, 2,
         1024, 4096, true, 0, true},
    };
    for (const auto& s : shapes) {
        std::ostringstream o;
        o << "# " << s.about << "\n";
        if (s.env) {
            o << "env " << s.env << " 0\n";
        }
        o << "region W watched " << hex(CARD_BASE) << " " << hex(s.size) << "\nwrite W 0 " << hex(s.size) << " 1\n";
        o << "card_shadow s W 0 " << hex(s.size) << "\nrefresh s 0 " << hex(s.size) << "\n";
        o << "prepare 1\ngpu_declare s 0 " << hex(s.size) << "\ncard_write s 0 0x10 2\ncard_submit s 0 " << hex(s.size) << "\nquiet 1\n";
        u64 pieces = s.size / K64;
        for (int i = 0; i < s.rounds; ++i) {
            for (int k = 0; k < s.title_writes; ++k) {
                o << "write W " << hex(r.below(pieces) * K64 + r.below(K64 - 64)) << " 32 " << i * 1000 + k + 3 << "\n";
            }
            o << "refresh s 0 " << hex(s.size) << "\n";
            if (s.relay) {
                o << "merge_under s 0 " << hex(s.size) << " 4096\n";
            }
            o << "prepare " << i + 2 << "\n";
            std::vector<std::pair<u64, u64>> declared;
            if (s.ranges == 0) {
                declared.emplace_back(0, s.size);
            } else {
                u64 step = s.size / static_cast<u64>(s.ranges);
                for (int k = 0; k < s.ranges; ++k) {
                    declared.emplace_back(k * step + r.below(step / 2), r.between(4, 12) * 1024);
                }
            }
            for (auto [off, len] : declared) {
                o << "gpu_declare s " << hex(off) << " " << hex(len) << "\n";
            }

            std::vector<u64> order;
            if (s.spread) {
                for (u64 p = 0; p < pieces; ++p) {
                    order.push_back(p);
                }
                for (u64 k = order.size() - 1; k > 0; --k) {
                    std::swap(order[k], order[r.below(k + 1)]);
                }
            }
            for (int k = 0; k < s.shader_writes; ++k) {
                u64 len = s.write_len ? s.write_len : r.between(4, 256);
                u64 off;
                if (s.spread) {
                    off = order[k] * K64 + r.below(K64 - len);
                } else if (s.ranges) {
                    auto [a, l] = declared[r.below(declared.size())];
                    off = a + r.below(l - len);
                } else {
                    off = r.below(s.size - len);
                }
                o << "card_write s " << hex(off) << " " << hex(len) << " " << i * 10000 + k + 1 << "\n";
            }
            o << (s.relay ? "card_send" : "card_submit");
            for (auto [off, len] : declared) {
                o << " s " << hex(off) << " " << hex(len);
            }
            o << "\n";
            if (s.relay && i > 0) {
                o << "card_land 1\n";
            }
        }
        if (s.relay) {
            o << "card_land\n";
        }

        o << "quiet 0\ncheck\ncard_check s\n";
        put(s.name, o.str());
    }
}


std::string generate_util(u64 seed) {
    Rng r{seed * 0x51ED27 + 7};
    std::ostringstream o;
    const u64 MB = 1 << 20;
    o << "# utility fuzz, seed " << seed << "\nregion U plain " << hex(BASE + 0x7000000000ull) << " " << hex(4 * MB) << "\n";
    o << "write U 0 " << hex(4 * MB) << " " << seed + 1 << "\n";
    const char* levels[] = {"-", "0", "1", "2", "3", "yes", "01", "+1"};
    const char* everys[] = {"-", "0", "1", "8", "32", "x", "+5", "007", "18446744073709551616"};
    auto big = [&]() -> u64 {
        switch (r.below(5)) {
            case 0: return 0;
            case 1: return r.below(64) * MB;
            case 2: return r.below(16) << 30;
            case 3: return (u64{1} << 62) + r.below(1000);
            default: return r.next() >> 2;
        }
    };
    int ops = 40 + static_cast<int>(r.below(80));
    for (int i = 0; i < ops; ++i) {
        switch (r.below(9)) {
            case 0: o << "rebar_level " << levels[r.below(std::size(levels))] << "\n"; break;
            case 1: o << "rebar_most " << (r.chance(20) ? std::string("-") : std::to_string(big())) << "\n"; break;
            case 2: {
                u64 budget = big();
                o << "rebar_decide " << r.below(4) << " " << r.below(2) << " " << (r.chance(50) ? "window" : "buffer") << " " << big() << " "
                  << (r.chance(20) ? 1 : 0) << " " << big() << " " << big() << " " << (r.chance(20) ? std::string("-") : std::to_string(budget))
                  << " " << (r.chance(50) ? saturating_sub(budget / 10 * 8, r.below(3) * MB) + r.below(2) : big()) << "\n";
                break;
            }
            case 3:
            case 4: {
                u64 a = r.below(64) * 16, b = a + r.below(5) * 16;
                o << "ranges_insert " << a << " " << b << "\n";
                break;
            }
            case 5: o << (r.chance(50) ? "ranges_remove_at " + std::to_string(r.below(64) * 16) : "ranges_remove " + std::to_string(r.below(64) * 16) + " " + std::to_string(r.below(80) * 16)) << "\n"; break;
            case 6: {
                u64 a = r.below(1100), b = r.chance(10) ? a : a + r.below(200);
                o << "ranges_overlaps " << a << " " << b << "\n";
                break;
            }
            case 7: {
                u64 len = r.chance(30) ? r.below(130) : r.below(4 * MB / 2);
                o << "lane_hash U " << hex(r.below(4 * MB - len)) << " " << hex(len) << "\n";
                break;
            }
            default:
                if (r.chance(50)) {
                    o << "check_turn " << r.next() / 4 << " " << r.next() / 4 << " " << r.below(10) << "\n";
                } else {
                    o << "hash_every " << everys[r.below(std::size(everys))] << "\n";
                }
        }
    }
    o << "end\n";
    return o.str();
}


std::vector<std::wstring> loaders_running() {
    std::vector<std::wstring> found;
    HANDLE snap = CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0);
    if (snap == INVALID_HANDLE_VALUE) {
        return found;
    }
    PROCESSENTRY32W e{};
    e.dwSize = sizeof e;
    for (BOOL ok = Process32FirstW(snap, &e); ok; ok = Process32NextW(snap, &e)) {
        for (const wchar_t* name : {L"DanziLoader.exe", L"danzi-container.exe", L"victory.exe", L"game_scarlett_master.exe"}) {
            if (_wcsicmp(e.szExeFile, name) == 0) {
                found.push_back(e.szExeFile);
            }
        }
    }
    CloseHandle(snap);
    return found;
}

struct Timed {
    std::vector<double> per_op_ns;   
    double total_ns = 0;
};


std::map<std::string, Timed> read_timing(const fs::path& out, size_t first_op) {
    std::map<std::string, Timed> t;
    std::istringstream in(read_file(out / "timing.txt"));
    size_t op;
    std::string name;
    double ns;
    while (in >> op >> name >> ns) {
        if (op > first_op) {
            t[name].per_op_ns.push_back(ns);
            t[name].total_ns += ns;
        }
    }
    return t;
}

double percentile(std::vector<double> v, double p) {
    if (v.empty()) {
        return 0;
    }
    std::sort(v.begin(), v.end());
    size_t i = static_cast<size_t>(p * static_cast<double>(v.size() - 1) + 0.5);
    return v[std::min(i, v.size() - 1)];
}

int bench(const fs::path& dir, const fs::path& oracle, const fs::path& cpp, const fs::path& work, int runs, DWORD_PTR cpu) {
    if (auto busy = loaders_running(); !busy.empty()) {
        std::printf("bench: refusing to measure while a loader runs (%ls)\n", busy.front().c_str());
        return 4;
    }
    std::vector<fs::path> files;
    for (const auto& e : fs::directory_iterator(dir)) {
        if (e.path().extension() == ".txt") {
            files.push_back(e.path());
        }
    }
    std::sort(files.begin(), files.end());
    std::printf("%-34s %5s | %12s %12s %12s | %12s %12s %12s | %6s %7s\n", "fixture:operation", "ops", "rust med/op", "rust p95", "rust total",
                "c++ med/op", "c++ p95", "c++ total", "c/r", "speedup");
    int mismatches = 0;
    for (const auto& f : files) {


        size_t quiet_op = 0, n = 0;
        bool quiet_seen = false;
        for (const auto& l : lines_of(read_file(f))) {
            std::string t = l.substr(0, l.find('#'));
            if (t.find_first_not_of(" \t") == std::string::npos) {
                continue;
            }
            if (!quiet_seen && t.find("quiet") == t.find_first_not_of(" \t")) {
                quiet_op = n;
                quiet_seen = true;
            }
            ++n;
        }
        struct Kind {
            std::vector<double> rust_totals, cpp_totals, rust_ops, cpp_ops;
        };
        std::map<std::string, Kind> kinds;
        for (int run = 0; run < runs; ++run) {
            fs::path w = work / f.stem() / std::to_string(run);
            fs::remove_all(w);
            fs::create_directories(w);

            bool oracle_first = run % 2 == 0;
            for (int side = 0; side < 2; ++side) {
                bool is_oracle = (side == 0) == oracle_first;
                run_exe(is_oracle ? oracle : cpp, f, w / (is_oracle ? "oracle" : "cpp"), cpu);
            }
            auto c = compare(w / "oracle", w / "cpp");
            if (!c.match) {
                ++mismatches;
                std::printf("%s run %d: MISMATCH\n  %s\n", f.stem().string().c_str(), run, c.detail.c_str());
            }
            auto a = read_timing(w / "oracle", quiet_op), b = read_timing(w / "cpp", quiet_op);
            for (auto& [name, t] : a) {
                auto& k = kinds[name];
                k.rust_totals.push_back(t.total_ns);
                k.rust_ops.insert(k.rust_ops.end(), t.per_op_ns.begin(), t.per_op_ns.end());
            }
            for (auto& [name, t] : b) {
                auto& k = kinds[name];
                k.cpp_totals.push_back(t.total_ns);
                k.cpp_ops.insert(k.cpp_ops.end(), t.per_op_ns.begin(), t.per_op_ns.end());
            }
            fs::copy_file(w / "oracle" / "timing.txt", work / (f.stem().string() + "-run" + std::to_string(run) + "-rust-timing.txt"),
                          fs::copy_options::overwrite_existing);
            fs::copy_file(w / "cpp" / "timing.txt", work / (f.stem().string() + "-run" + std::to_string(run) + "-cpp-timing.txt"),
                          fs::copy_options::overwrite_existing);
            fs::remove_all(w);
        }
        for (auto& [name, k] : kinds) {
            double rm = percentile(k.rust_ops, 0.5), cm = percentile(k.cpp_ops, 0.5);
            std::string label = f.stem().string().substr(0, 22) + ":" + name;
            std::printf("%-34s %5zu | %10.1fus %10.1fus %10.2fms | %10.1fus %10.1fus %10.2fms | %6.3f %6.2fx\n", label.c_str(),
                        k.rust_ops.size() / static_cast<size_t>(runs), rm / 1e3, percentile(k.rust_ops, 0.95) / 1e3,
                        percentile(k.rust_totals, 0.5) / 1e6, cm / 1e3, percentile(k.cpp_ops, 0.95) / 1e3, percentile(k.cpp_totals, 0.5) / 1e6,
                        rm > 0 ? cm / rm : 0.0, cm > 0 ? rm / cm : 0.0);
        }
        std::fflush(stdout);
    }
    if (auto busy = loaders_running(); !busy.empty()) {
        std::printf("bench: a loader started during the measurement (%ls): results not valid\n", busy.front().c_str());
        return 4;
    }
    std::printf("bench: %d runs per fixture, both sides pinned to CPU mask 0x%llx, %d log mismatches; med/op and p95 over every timed operation of "
                "every run, total = median over runs\n",
                runs, static_cast<unsigned long long>(cpu), mismatches);
    return mismatches ? 1 : 0;
}

