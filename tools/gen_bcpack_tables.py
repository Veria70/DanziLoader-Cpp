"""Writes src/formats/bcpack_tables.inc, the BCPack tables the port ships
with, as the body of a C++ byte-array initializer, from the reference's table
file (`victory-formats/src/bcpack-tables.bin`; DanziLoader / victory-perf, see
NOTICE.md).

Usage: python -I tools/gen_bcpack_tables.py <bcpack-tables.bin> <out.inc>
"""
import sys

data = open(sys.argv[1], 'rb').read()
lines = ['// SPDX-License-Identifier: GPL-3.0-or-later',
         '// The BCPack tables (`victory-formats/src/bcpack-tables.bin`; DanziLoader /',
         '// victory-perf, see NOTICE.md), %d bytes, as a byte-array initializer.' % len(data),
         '// Generated by tools/gen_bcpack_tables.py; do not edit.']
for at in range(0, len(data), 16):
    lines.append(','.join('0x%02x' % b for b in data[at:at + 16]) + ',')
open(sys.argv[2], 'wb').write(('\n'.join(lines) + '\n').encode('ascii'))
