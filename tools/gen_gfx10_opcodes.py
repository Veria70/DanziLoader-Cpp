import re
import sys

ref, out = sys.argv[1], sys.argv[2]
src = open(f'{ref}/crates/victory-shader/src/gfx10/opcodes.rs', encoding='utf-8').read()
notice = []
for line in src.splitlines():
    if not line.startswith('//'):
        break
    notice.append(line)
tables = re.findall(r'pub\(super\) const (\w+): &\[\(u16, &str\)\] = &\[(.*?)\];', src, re.S)
lines = ['// Generated by tools/gen_gfx10_opcodes.py from the reference\'s', '// crates/victory-shader/src/gfx10/opcodes.rs, which carries:', '//']
lines += notice
lines.append('')
for name, body in tables:
    entries = re.findall(r'\((0x[0-9a-fA-F]+),\s*"([^"]+)"\)', body)
    lines.append(f'inline constexpr Opcode {name}[] = {{')
    for op, n in entries:
        lines.append(f'    {{{op}, "{n}"}},')
    lines.append('};')
    lines.append('')
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print(f'{len(tables)} tables')
