import hashlib
import sys

ref, out = sys.argv[1], sys.argv[2]
path = ref + '/crates/victory-gpu/src/host.rs'
text = open(path, encoding='utf-8').read()
head = 'pub(crate) const CARD_COMPARE: &str = r#"'
start = text.index(head) + len(head)
end = text.index('"#;', start)
hlsl = text[start:end]
assert ')hlsl"' not in hlsl
line = text[:start].count('\n') + 1
digest = hashlib.sha256(text.encode('utf-8')).hexdigest()
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/take_card_compare.py from the reference\'s host.rs\n')
    f.write(f'// (CARD_COMPARE, line {line}; host.rs sha256 {digest}). Do not edit.\n')
    f.write('R"hlsl(' + hlsl + ')hlsl"\n')
print(f'{len(hlsl)} bytes from line {line}')
