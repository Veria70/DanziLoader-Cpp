"""M6.5: writes src/hle/table.cpp, the runtime's table of modules (their
names, the DLL names they serve, their export names, in the reference's
order) from `m6-oracle hle-registry`'s dump. Exports a module of the port
implements are bound in `table.cpp` by hand afterwards (`implemented`); the
rest point to a stub that traps with the export's name (`not ported`).

Usage: python -I tools/gen_hle_table.py <registry dump> <out.cpp>
"""
import sys

modules = []
for line in open(sys.argv[1], encoding='utf-8'):
    line = line.rstrip('\n')
    if line.startswith('module '):
        head, dlls = line[len('module '):].rsplit(' dlls=', 1)
        modules.append((head, dlls.split(','), []))
    elif line.startswith(' export '):
        modules[-1][2].append(line[len(' export '):])

out = ['// SPDX-License-Identifier: GPL-3.0-or-later',
       '// The runtime\'s table (`victory-hle`: each module\'s `module()`, in',
       '// `modules::all`\'s order; DanziLoader / victory-perf, see NOTICE.md).',
       '// Generated by tools/gen_hle_table.py from the reference\'s table, then',
       '// edited as modules are ported: an export with no address here is bound',
       '// to a stub that traps with its name (`registry.cpp`).',
       '#include "registry.hpp"',
       '',
       'namespace danzi::hle {',
       '',
       'std::vector<HleModule> all_modules() {',
       '    std::vector<HleModule> all;']
for name, dlls, exports in modules:
    out.append(f'    all.push_back(HleModule{{"{name}",')
    out.append('                            {' + ', '.join(f'"{d}"' for d in dlls) + '},')
    out.append('                            {')
    for e in exports:
        out.append(f'                                {{"{e}", 0}},')
    out.append('                            }});')
out += ['    return all;', '}', '', '}  // namespace danzi::hle', '']
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print(f'{len(modules)} modules, {sum(len(m[2]) for m in modules)} exports')
